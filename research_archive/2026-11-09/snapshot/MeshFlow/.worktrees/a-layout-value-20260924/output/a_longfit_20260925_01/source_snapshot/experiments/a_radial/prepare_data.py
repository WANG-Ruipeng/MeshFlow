"""Prepare BOTH methods from identical raw parents. All outputs go to a NEW root."""
from __future__ import annotations
from pathlib import Path
import argparse,json
import numpy as np
from .io_utils import file_hash,array_hash,new_dir,write_json,save_npz,read_mesh
from .mesh_ops import bisect_to_faces,ray_hits,topology
from .exporter import ASSETS,RadialSupport

def edge_metadata(v,f):
    e=np.unique(np.sort(np.vstack([f[:,[0,1]],f[:,[1,2]],f[:,[2,0]]]),axis=1),axis=0)
    length=np.linalg.norm(v[e[:,0]]-v[e[:,1]],axis=1);vert=np.full(len(v),np.inf)
    np.minimum.at(vert,e[:,0],length);np.minimum.at(vert,e[:,1],length)
    if not np.isfinite(vert).all() or length.min()<=0:raise ValueError('Bad edge metadata')
    return vert,float(length.min())

def build(manifest,outdir):
    manifest=Path(manifest);items=json.loads(manifest.read_text());objs=items['objects']
    if len(objs)!=16 or len({o['uid'] for o in objs})!=16:raise ValueError('Locked16 parents required')
    if any(o['source_split']!='train' for o in objs):raise ValueError('Do not add official test parents')
    root=new_dir(outdir);(root/'meshflow512/objaverse_occ_v5_ids').mkdir(parents=True);(root/'lineage').mkdir();(root/'raw').mkdir()
    sp=RadialSupport();all_y=[];records=[];rows=[]
    for obj in sorted(objs,key=lambda x:x['uid']):
        uid=obj['uid'];p=manifest.parent/obj['relative_path']
        if file_hash(p)!=obj['sha256']:raise ValueError(f'Raw hash mismatch: {uid}')
        v,f=read_mesh(p);sv,sf,parent,steps,proof=bisect_to_faces(v,f,512)
        # Compare actual surface radial queries, not only file face count.
        centre=(v.min(0)+v.max(0))/2;diag=np.linalg.norm(np.ptp(v,axis=0))
        c0,r0=ray_hits((v-centre)/diag,f,sp.u);c1,r1=ray_hits((sv-centre)/diag,sf,sp.u)
        if not np.all(c0==1) or not np.all(c1==1):raise ValueError('Single radial hit failed after subdivision')
        delta=float(abs(r0-r1).max())
        if delta>1e-10:raise ValueError('Geometry/radius changed during subdivision')
        rs=float(np.sqrt(np.mean(r0*r0)));y=np.log(r0/rs).astype(np.float32);all_y.append(y)
        vl,ml=edge_metadata(sv,sf)
        save_npz(root/'meshflow512/objaverse_occ_v5_ids'/f'{uid}.npz',vertices=sv,faces=sf,uid=np.array(uid),vertices_num=np.array(len(sv)),faces_num=np.array(len(sf)),min_length=np.array(ml),vertices_min_length=vl)
        save_npz(root/'lineage'/f'{uid}.npz',face_to_original=parent,edge_splits=steps,centre=centre,bbox_diagonal=np.array(diag),model_to_input_scale=np.array(diag*rs))
        (root/'raw'/p.name).write_bytes(p.read_bytes())
        records.append({'uid':uid,'vertices_num':len(sv),'faces_num':len(sf),'min_length':ml})
        rows.append({'uid':uid,'raw_sha256':obj['sha256'],'raw_faces':len(f),'faces':len(sf),'face_bin':len(sf)//20,'subdivision_splits':len(steps),**proof,'max_raw_refined_radial_diff_bbox':delta,'refined_sha256':file_hash(root/'meshflow512/objaverse_occ_v5_ids'/f'{uid}.npz')})
    # Upstream dataset expects object dictionaries; these are generated by us, not arbitrary untrusted pickles.
    for split in ['train','test']:
        save_npz(root/'meshflow512/split'/f'{split}.npz',npz_list=np.array(records,dtype=object))
    write_json(root/'meshflow512/CLOSED_SET_NOTICE.json',{'train_equals_test_intentionally':True,'purpose':'Upstream loader compatibility. test.npz is a training-support copy, NOT held-out validation/test. Never use it to claim generalization.','official_original_test_used':False})
    save_npz(root/'radial_train.npz',logr=np.stack(all_y),uids=np.array([x['uid'] for x in records]))
    write_json(root/'DATASET.json',{'schema':1,'role':'closed_set_training_support_only','parents_sha256':file_hash(manifest),'source_archive_sha256':items['source_archive_sha256'],'num_parents':16,'target_faces':512,'source_dtype_preserved_in_float64':True,'radial_dtype':'float32','radial_sha256':file_hash(root/'radial_train.npz'),'rows':rows,'same_parent_geometric_surface':True,'loader_gate_status':'NOT_RUN; run official_contract before external training','no_meshflow_fit_claim':True})
    return root

def main():
    p=argparse.ArgumentParser();p.add_argument('--manifest',default=str(ASSETS/'parents.json'));p.add_argument('--out',required=True);a=p.parse_args()
    print(build(a.manifest,a.out))
if __name__=='__main__':main()
